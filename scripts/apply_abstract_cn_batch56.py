def main():
    conn = sqlite3.connect(DB)
    conn.row_factory = sqlite3.Row
    cur = conn.cursor()
    updated = 0
    for lid, cn in ABSTRACT_CN.items():
        cur.execute("SELECT id, abstract FROM literature WHERE id=?", (lid,))
        r = cur.fetchone()
        if not r:
            print(f"跳过不存在: {lid}")
            continue
        if not r['abstract']:
            print(f"跳过无摘要: {lid}")
            continue
        cur.execute("UPDATE literature SET abstract_cn=?, updated_at=datetime('now') WHERE id=?",
                    (cn, lid))
        updated += 1
    conn.commit()
    conn.close()
    print(f"✅ 批次56完成，更新 {updated}/{len(ABSTRACT_CN)} 篇中文摘要")

if __name__ == '__main__':
    main()
